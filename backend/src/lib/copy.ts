export type CopyKey = keyof typeof STRINGS;

export function t(language: AppLanguageCode, key: CopyKey, vars: Record<string, string | number> = {}) {
  const template: string = STRINGS[key][language] ?? STRINGS[key].en;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
}

/** Shortens a quoted line at a word boundary. */
export function quote(line: string, max = 90) {
  const text = line.trim().replace(/\s+/g, " ");
  if (text.length <= max) return text;
  const cut = text.slice(0, max).replace(/\s+\S*$/, "") || text.slice(0, max);
  return `${cut.replace(/[,;:\s]+$/, "")}…`;
}
